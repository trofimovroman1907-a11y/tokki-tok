    private static E e(String id, String name, int hp, int dmg, int top, int money, String music, String sprite, float scale, int need) {
        E e = new E();
        e.name = name;
        e.hp = hp;
        e.dmg = dmg;
        e.top = top;
        e.money = money;
        e.music = music;
        e.sprite = sprite;
        e.scale = scale;
        e.need = need;
        ALL.put(id, e);
        return e;
    }

