    static final class Act {
        String t, needs, tNo, flag, onceT;
        int spare, rage;
        boolean repeat;
        String[] react = new String[0];

        Act(String t) { this.t = t; }
        Act needs(String n, String no) { needs = n; tNo = no; return this; }
        Act flag(String f) { flag = f; return this; }
        Act spare(int s) { spare = s; return this; }
        Act repeat() { repeat = true; return this; }
        Act once(String o) { onceT = o; return this; }
        Act rage(int r) { rage = r; return this; }
        Act react(String... r) { react = r; return this; }
    }

